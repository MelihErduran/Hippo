import type { Store } from '../store/store.js';
import { fmtAbsolute, localDateKey } from '../time.js';
import type { BriefContent, Item } from '../types.js';

// One-way markdown mirror: the database is the source of truth, these files
// are regenerated after each change so you can read everything in Obsidian.

const HEADER = '<!-- Generated by Hippo. Edits here are overwritten; use the hippo CLI. -->\n\n';

function taskLine(t: Item, _now: number, slug: (id: number | null) => string | null): string {
  const due = t.dueAt ? ` · due ${fmtAbsolute(t.dueAt)}` : t.remindAt ? ` · remind ${fmtAbsolute(t.remindAt)}` : '';
  const proj = slug(t.projectId);
  return `- [${t.status === 'done' ? 'x' : ' '}] #${t.id} ${t.title}${proj ? ` · [[${proj}]]` : ''}${due}`;
}

export function renderBrief(b: BriefContent, _now?: number): string {
  const lines = [`# ${b.date}`, '', b.headline, '', '## Top 3', ''];
  b.top3.forEach((p, i) => {
    lines.push(`${i + 1}. **${p.title}** (#${p.taskId})${p.dueAt ? ` · due ${fmtAbsolute(p.dueAt)}` : ''}`);
    lines.push(`    - Why: ${p.why}`);
    lines.push(`    - First step: ${p.firstStep}`);
  });
  if (b.blocks.length) {
    lines.push('', '## Plan', '');
    for (const bl of b.blocks) lines.push(`- ${bl.start}-${bl.end} ${bl.fixed ? bl.label : `**${bl.label}**`}`);
  }
  if (b.defer.length) {
    lines.push('', '## Not today', '');
    for (const d of b.defer) lines.push(`- #${d.taskId} ${d.title}: ${d.reason}`);
  }
  if (b.note) lines.push('', b.note);
  return lines.join('\n') + '\n';
}

/** Path (relative to the mirror dir) -> file content. */
export function renderMirror(store: Store, now: number): Map<string, string> {
  const files = new Map<string, string>();
  const projects = store.listProjects();
  const slugById = new Map(projects.map((p) => [p.id, p.slug]));
  const slug = (id: number | null) => (id === null ? null : slugById.get(id) ?? null);
  const items = store.allItems();
  const byProjectThenDue = (a: Item, b: Item) => {
    const sa = slug(a.projectId) ?? '\uffff';
    const sb = slug(b.projectId) ?? '\uffff';
    if (sa !== sb) return sa < sb ? -1 : 1;
    return (a.dueAt ?? Infinity) - (b.dueAt ?? Infinity) || a.id - b.id;
  };
  const open = items.filter((i) => i.kind === 'task' && i.status === 'open').sort(byProjectThenDue);

  const overdue = open.filter((t) => t.dueAt !== null && t.dueAt < now);
  const soon = open.filter((t) => t.dueAt !== null && t.dueAt >= now);
  const someday = open.filter((t) => t.dueAt === null);
  const section = (title: string, list: Item[]) =>
    list.length ? `## ${title}\n\n${list.map((t) => taskLine(t, now, slug)).join('\n')}\n\n` : '';
  files.set('Tasks.md', `${HEADER}# Tasks\n\n${section('Overdue', overdue)}${section('Coming up', soon)}${section('Someday', someday)}`
    .trimEnd() + '\n');

  const ideas = items.filter((i) => i.kind === 'idea' && i.status !== 'dropped').sort((a, b) => b.createdAt - a.createdAt);
  files.set('Ideas.md', `${HEADER}# Ideas\n\n${ideas.map((i) =>
    `- ${i.title}${slug(i.projectId) ? ` · [[${slug(i.projectId)}]]` : ''} · ${localDateKey(i.createdAt)}${i.body ? `\n    - ${i.body}` : ''}`).join('\n')}\n`);

  for (const p of projects) {
    const mine = items.filter((i) => i.projectId === p.id && i.status !== 'dropped');
    const cps = store.checkpointsFor(p.id, 5);
    const parts = [`${HEADER}# ${p.name}`, '', `Last touched ${fmtAbsolute(p.lastTouchedAt)}`, ''];
    if (cps.length) {
      parts.push('## Where I left off', '');
      for (const c of cps) parts.push(`- ${fmtAbsolute(c.createdAt)}: ${c.summary}${c.nextStep ? ` → next: ${c.nextStep}` : ''}`);
      parts.push('');
    }
    const openMine = mine.filter((i) => i.kind === 'task' && i.status === 'open');
    if (openMine.length) parts.push('## Open tasks', '', ...openMine.map((t) => taskLine(t, now, slug)), '');
    const notes = mine.filter((i) => i.kind !== 'task');
    if (notes.length) parts.push('## Notes and ideas', '', ...notes.map((n) => `- ${n.kind === 'idea' ? 'Idea: ' : ''}${n.title}`), '');
    const done = mine.filter((i) => i.kind === 'task' && i.status === 'done').slice(0, 10);
    if (done.length) parts.push('## Recently done', '', ...done.map((t) => taskLine(t, now, slug)), '');
    files.set(`Projects/${p.slug}.md`, parts.join('\n'));
  }

  const brief = store.getBrief(localDateKey(now));
  if (brief) files.set(`Daily/${brief.date}.md`, HEADER + renderBrief(brief, now));
  return files;
}
